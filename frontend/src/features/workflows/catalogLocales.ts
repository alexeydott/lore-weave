/** RU overlay only — any other locale (or a missing entry) falls back. */
function lookupRu(m: Record<string, string>, locale: string | undefined, key: string, fallback: string): string {
  const base = locale?.split('-')[0];
  if (base !== 'ru') return fallback;
  return m[key] ?? fallback;
}

export function localizedWorkflowTitle(locale: string | undefined, slug: string, fallback: string): string {
  return lookupRu(WORKFLOW_TITLES_RU, locale, slug, fallback);
}

export function localizedWorkflowDescription(locale: string | undefined, slug: string, fallback: string): string {
  return lookupRu(WORKFLOW_DESCRIPTIONS_RU, locale, slug, fallback);
}
